func TestParseSequenceDiagram(t *testing.T) {
	d, err := ParseSequence(mermaid, 1)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(d.Participants, []string{"Client", "Server", "Database"}) {
		t.Fatalf("participants %v", d.Participants)
	}
	var ids []string
	for _, m := range d.Messages {
		ids = append(ids, m.ID)
	}
	if !slices.Equal(ids, []string{"M1", "M2", "M3", "M4", "M5"}) {
		t.Fatalf("ids %v", ids)
	}
	m0 := d.Messages[0]
	if m0.Sender != "Client" || m0.Receiver != "Server" || m0.Text != "GET /users" || m0.Kind != "call" {
		t.Fatalf("message 0 %+v", m0)
	}
	if d.Messages[2].Kind != "reply" {
		t.Fatalf("message 2 kind %q", d.Messages[2].Kind)
	}
	if !slices.Equal(d.Messages[3].Context, []string{"alt service unavailable"}) || len(d.Messages[4].Context) != 0 {
		t.Fatalf("contexts %v %v", d.Messages[3].Context, d.Messages[4].Context)
	}
	mustContain(t, d.ToAnnotated(), "M2: Server -[call]-> Database: Query Users")
}

