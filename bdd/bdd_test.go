// Go-specific gate rules: goroutines, directives, cgo, aliased imports and
// attempts to break out of the snippet's context.
func TestScanPlanGoSpecificRules(t *testing.T) {
	cases := []struct {
		name string
		plan *TestPlan
		want string
	}{
		{"goroutine of unknown code", planWith(TestCase{Given: []string{"go m.Run()"}, When: "nil"}), "go statement is only allowed with an inline func literal"},
		{"directive", planWith(TestCase{Given: []string{"//go:linkname x runtime.x", "x := 1"}, When: "nil"}), "compiler directive is not allowed (//go:linkname x runtime.x)"},
		{"break out of the body", planWith(TestCase{Given: []string{"}", "func init() { panic(1) }", "func _() {"}, When: "nil"}), "case 'test_x' given: not valid Go"},
		{"break out of the expression", planWith(TestCase{Then: []string{"true) { }; if (true"}}), "case 'test_x' then[0]: not valid Go"},
		{"package clause", planWith(TestCase{Given: []string{"package main"}, When: "nil"}), "package clause is not allowed"},
	}
	for _, tc := range cases {
		if p := ScanPlan(tc.plan); !anyContains(p, tc.want) {
			t.Errorf("%s: problems %v, want %q", tc.name, p, tc.want)
		}
	}
	// goroutines of inline, screened code are fine
	if p := ScanPlan(planWith(TestCase{Given: []string{"done := make(chan int)", "go func() { done <- m.F() }()"}, When: "<-done"})); len(p) != 0 {
		t.Fatalf("problems %v", p)
	}

	imports := planWith(TestCase{})
	imports.API.Imports = []string{`"os/exec"`, `x "os"`, `import "C"`, `"net/http"`, `"errors"`, "example.com/m", `"unterminated`}
	want := []string{
		"api imports[0]: import of 'os/exec' is not allowed",
		"api imports[1]: import of 'os' is not allowed",
		"api imports[2]: import of 'C' is not allowed",
		"api imports[3]: import of 'net/http' is not allowed",
	}
	p := ScanPlan(imports)
	if len(p) != 5 || !slices.Equal(p[:4], want) || !strings.HasPrefix(p[4], "api imports[6]: not a valid Go import spec") {
		t.Fatalf("problems %q", p)
	}
}

func TestBuildSafetyGateBlocksAndWritesNothingRunnable(t *testing.T) {
	// Plan mode, so no planner call is needed: proves the gate guards the
	// LLM-free path too (a malicious hand-authored / PR-supplied .toml).
	hostile := `[meta]
feature_name = "Evil"
[api]
module = "example.com/m"
signatures = ["func F() int"]
[[cases]]
test_name = "test_pwn"
scenario = "pwn"
when = 'exec.Command("id").Run()'
then = ["result == nil"]
`
	dir := t.TempDir()
	specFile := filepath.Join(dir, "evil.toml")
	if err := os.WriteFile(specFile, []byte(hostile), 0o644); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, "generated")
	planner := &countingPlanner{}

	_, err := Build(context.Background(), specFile, out, Options{Planner: planner, Lenient: true})
	var serr *PlanSafetyError
	if !errors.As(err, &serr) || !strings.Contains(err.Error(), "exec") {
		t.Fatalf("err %v", err)
	}
	if _, err := os.Stat(filepath.Join(out, "evil.plan.json")); err != nil {
		t.Fatal("plan JSON not kept for inspection")
	}
	if _, err := os.Stat(filepath.Join(out, "evil_test.go")); err == nil {
		t.Fatal("runnable test file written")
	}
	if planner.calls != 0 {
		t.Fatal("plan mode consulted the planner")
	}
}

