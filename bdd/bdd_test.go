func TestValidatePlanFlagsAllGapKinds(t *testing.T) {
	spec := mustParse(t, sequenceTOML)
	plan := spec.ToTestPlan()
	// claim an id that doesn't exist and a scenario that's declared but uncovered
	plan.Cases[0].Covers = []string{"M1", "M99"}
	scenarios := spec.ScenarioNames()
	scenarios["Listing users elsewhere"] = true
	problems := ValidatePlan(plan, scenarios, spec.MessageIDs(), spec.RequiredIDs())
	want := []string{
		"scenario not covered by any test case: 'Listing users elsewhere'",
		"test case claims unknown id: 'M99'",
		"sequence message not covered by any test case: M2",
		"sequence message not covered by any test case: M3",
		"sequence message not covered by any test case: M4",
		"sequence message not covered by any test case: M5",
	}
	if !slices.Equal(problems, want) {
		t.Fatalf("problems\n%q\nwant\n%q", problems, want)
	}
	// a sound plan for the plan-mode spec has no problems
	good := mustParse(t, planTOML)
	if p := ValidatePlan(good.ToTestPlan(), good.ScenarioNames(), good.MessageIDs(), good.RequiredIDs()); len(p) != 0 {
		t.Fatalf("problems %v", p)
	}
}

