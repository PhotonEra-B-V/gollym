func TestBuildWritesSuitePlanAndBrief(t *testing.T) {
	_, chatOpts := mockPlanner(t)
	dir := t.TempDir()
	specFile := filepath.Join(dir, "retry.toml")
	if err := os.WriteFile(specFile, []byte(requestTOML), 0o644); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, "generated")

	// samplePlan does not cover rule_1/edge_1, so run lenient to still write files.
	results, err := Build(context.Background(), specFile, out, Options{Chat: chatOpts, Lenient: true})
	if err != nil {
		t.Fatal(err)
	}
	if len(results) != 1 {
		t.Fatalf("results %d", len(results))
	}
	r := results[0]
	if r.TestPath != filepath.Join(out, "retry_policy_test.go") {
		t.Fatalf("test path %s", r.TestPath)
	}
	src, _ := os.ReadFile(r.TestPath)
	mustParseGo(t, string(src))
	mustContain(t, string(src), "//go:build bdd_pending", "package generated")
	saved, _ := os.ReadFile(r.PlanPath)
	reloaded, err := ParsePlan(saved)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(reloaded, r.Plan) {
		t.Fatalf("plan JSON round trip differs:\n%+v\n%+v", reloaded, r.Plan)
	}
	brief, _ := os.ReadFile(r.BriefPath)
	mustContain(t, string(brief), "func Backoff(attempt int, base float64) float64", "TestNegativeAttemptRejected",
		"read-only", "go test -tags bdd_pending "+out)
}

